"""M9 listening-history acceptance: synthetic fixtures drive the real stats.cpp engine.

The project's pinned zig compiler builds a small generated harness against src/stats.cpp (the
same translation unit the player ships) so the checks exercise the real engine, not a model of
it. Fixtures are written straight into a scratch data directory as listen-log.jsonl.

Covered:
  * day / month / year buckets follow the machine's local time, never UTC (midnight, month,
    year and daylight-saving boundaries),
  * Top-N, 24 hour buckets and availableKeys stay inside their bounds,
  * the projection handed to the model stays under 8 KB and carries no cookie, uid, stream URL
    or local path,
  * torn, invalid, oversized and CRLF lines are tolerated,
  * compaction above 16 MB keeps the newest listens,
  * flush is idempotent, a real track end replaces the approximate row,
  * concurrent readers stay safe while a writer appends.

Usage: python scripts/m9_stats_check.py [--force-build] [--keep]
"""
