"""Run the user's requested perfectPixel tool and embed its small indexed result."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TOOL = ROOT / 'tools/perfectPixel'
ASSET = ROOT / 'assets/amu'
if not (TOOL/'src/perfect_pixel').is_dir():
    raise SystemExit('Clone https://github.com/theamusing/perfectPixel into tools/perfectPixel and checkout 72096de5cf1bff9102687c4f89af6f62c4273a86. Then rerun this asset-only build script.')
sys.path.insert(0, str(TOOL / 'src'))
from perfect_pixel import get_perfect_pixel
from perfect_pixel.perfect_pixel_noCV2 import refine_grids, sample_majority

parser = argparse.ArgumentParser()
parser.add_argument('--size', type=int, default=48)
parser.add_argument('--colors', type=int, default=32)
args = parser.parse_args()
if not 32 <= args.size <= 64 or not 16 <= args.colors <= 64:
    parser.error('size must be 32..64 and colors 16..64')

source = ASSET / 'amu-source.png'
rgba = np.asarray(Image.open(source).convert('RGBA'))
matte = np.array([24,23,30], dtype=np.float32)
alpha = rgba[:,:,3:4].astype(np.float32)/255
rgb = np.rint(rgba[:,:,:3]*alpha + matte*(1-alpha)).astype(np.uint8)
# The public RGB pipeline is the upstream algorithm, with a fixed terminal-sized grid.
width, height, refined = get_perfect_pixel(
    rgb, sample_method='majority', grid_size=(args.size,args.size),
    refine_intensity=.18, fix_square=False, debug=False,
)
# Use the exact same upstream grid for alpha, rather than inventing an unrelated mask.
x_grid, y_grid = refine_grids(rgb,args.size,args.size,refine_intensity=.18)
sampled_rgba = sample_majority(rgba,x_grid,y_grid)
if sampled_rgba.shape[:2] != refined.shape[:2]:
    raise RuntimeError('perfectPixel RGB/alpha grids differ')
refined_rgba = np.dstack((refined, np.where(sampled_rgba[:,:,3]>=160,255,0).astype(np.uint8)))
refined_rgba[refined_rgba[:,:,3]==0,:3]=0
image = Image.fromarray(refined_rgba).quantize(colors=args.colors,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE).convert('RGBA')
refined_size=(width,height)
if height%2:
    padded=Image.new('RGBA',(width,height+1),(0,0,0,0))
    padded.paste(image,(0,0))
    image=padded
    height+=1
pixels = [tuple(map(int,p)) for p in np.asarray(image).reshape(-1,4)]
colors = sorted({p[:3] for p in pixels if p[3]>=128})
lookup = {color:index for index,color in enumerate(colors)}
indices = [lookup[p[:3]] if p[3]>=128 else 255 for p in pixels]
if not any(index==255 for index in indices):
    raise RuntimeError('Character asset must retain a transparent background')
if len(colors)>64 or width>64 or height>64:
    raise RuntimeError('Character exceeds embedded asset budget')
image.save(ASSET/'amu-pixel.png')
image.resize((width*12,height*12),Image.Resampling.NEAREST).save(ASSET/'amu-pixel-preview.png')
header = ['// Generated by scripts/build_amu_asset.py using perfectPixel. Do not hand-edit.',
          '#pragma once','#include <array>','#include <cstdint>','namespace mora::amu_asset {',
          f'inline constexpr int width={width}, height={height};',
          f'inline constexpr std::array<std::array<uint8_t,3>,{len(colors)}> palette = {{{{']
header += ['    {'+','.join(map(str,color))+'},' for color in colors]
header += ['}};',f'inline constexpr std::array<uint8_t,{width*height}> pixels = {{{{']
for row in range(height):
    header.append('    '+','.join(map(str,indices[row*width:(row+1)*width]))+',')
header += ['}};','} // namespace mora::amu_asset','']
(ASSET/'amu_sprite.hpp').write_text('\n'.join(header),encoding='utf-8')
try:
    commit=subprocess.check_output(['git','-c',f'safe.directory={TOOL.as_posix()}','-C',str(TOOL),'rev-parse','HEAD'],text=True).strip()
except subprocess.SubprocessError:
    commit='unknown'
provenance={
    'character':'阿木 / Amu',
    'reference':{'kind':'latest user conversation attachment','description':'Left-facing close-up portrait: water-blue short hair, white eyebrows, blue eyes, white/blue OVER-EAR headphones with Amu signature, white hoodie','emoteReferencesUsed':False},
    'generation':{'mode':'built-in image_gen','source':'amu-source.png','prompt':'prompt.txt'},
    'perfectPixel':{'repository':'https://github.com/theamusing/perfectPixel','commit':commit,'backend':'numpy/noCV2','grid':[args.size,args.size],'sample_method':'majority','refine_intensity':.18,'fix_square':False},
    'postprocess':{'paletteColors':len(colors),'dither':False,'alpha':'same refined grid; threshold160','refinedSize':list(refined_size),'transparentBottomPadding':height-refined_size[1]},
    'output':{'width':width,'height':height,'embeddedPixelsBytes':width*height,'paletteBytes':len(colors)*3,'staticPortrait':True},
    'sha256':{name:hashlib.sha256((ASSET/name).read_bytes()).hexdigest() for name in ['amu-source.png','amu-pixel.png','amu_sprite.hpp']},
}
(ASSET/'provenance.json').write_text(json.dumps(provenance,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps(provenance['output']))
